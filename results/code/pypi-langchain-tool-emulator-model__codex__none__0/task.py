"""Integration-test agent with LLM-emulated tools.

Running this module requires ANTHROPIC_API_KEY. Agent and emulator calls use
the LLM API, but no weather service or database is contacted. Emulated results
are synthetic and should not be treated as factual or deterministic fixtures.
"""

from langchain.agents import create_agent
from langchain.agents.middleware import LLMToolEmulator
from langchain.tools import tool


@tool
def get_weather(location: str) -> str:
    """Get current weather for a city or location, including temperature and conditions."""
    raise RuntimeError("get_weather must be intercepted by LLMToolEmulator")


@tool
def search_db(query: str) -> str:
    """Search the database with a natural-language query and return matching records."""
    raise RuntimeError("search_db must be intercepted by LLMToolEmulator")


def create_test_agent(model="anthropic:claude-sonnet-4-5-20250929"):
    """Build an agent whose tool results are generated by an LLM.

    Accepts a LangChain model identifier or a tool-capable chat model instance.
    """
    return create_agent(
        model=model,
        tools=[get_weather, search_db],
        middleware=[
            LLMToolEmulator(tools=[get_weather, search_db], model=model),
        ],
        system_prompt=(
            "You are an integration-test assistant. Use get_weather for weather "
            "questions and search_db for database questions. Tool results are "
            "synthetic test data; summarize them as simulated results."
        ),
    )


if __name__ == "__main__":
    agent = create_test_agent()
    result = agent.invoke(
        {
            "messages": [
                {
                    "role": "user",
                    "content": (
                        "Get the weather in Toronto and search the database for "
                        "outdoor venues in Toronto. Summarize both results."
                    ),
                }
            ]
        },
        config={"recursion_limit": 20},
    )
    print(result["messages"][-1].content)
